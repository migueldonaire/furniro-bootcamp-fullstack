// Uploads the product images (database/images/) to Supabase Storage
// and writes the SQL that changes the URLs in the database.
//
// Use (from the root of the repo):
//   1. cp database/.env.example database/.env   (and fill in the values)
//   2. node database/scripts/upload-images.mjs
//   3. Paste database/update-image-urls.sql into the SQL Editor of Supabase
//
// Needs Node.js 22 or newer. No libraries: it uses fetch.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DATABASE_DIR = join(import.meta.dirname, '..');
const IMAGES_DIR = join(DATABASE_DIR, 'images');
const ENV_FILE = join(DATABASE_DIR, '.env');
const SQL_FILE = join(DATABASE_DIR, 'update-image-urls.sql');

// The URL that seed.sql uses (the public repo on GitHub)
const SEED_BASE_URL =
  'https://raw.githubusercontent.com/migueldonaire/furniro-bootcamp-fullstack/main/database/images/';

if (existsSync(ENV_FILE)) process.loadEnvFile(ENV_FILE);

const SUPABASE_URL = process.env.SUPABASE_URL?.replace(/\/$/, '');
const KEY = process.env.SUPABASE_SECRET_KEY;
const BUCKET = process.env.SUPABASE_BUCKET ?? 'products';

if (!SUPABASE_URL || !KEY) {
  console.error('Faltan SUPABASE_URL o SUPABASE_SECRET_KEY en database/.env');
  process.exit(1);
}

// The secret key goes in "apikey". The old service_role key (a JWT, starts with "eyJ")
// also goes in Authorization.
const headers = { apikey: KEY };
if (KEY.startsWith('eyJ')) headers.Authorization = `Bearer ${KEY}`;

async function call(method, path, body, extraHeaders = {}) {
  const response = await fetch(`${SUPABASE_URL}/storage/v1${path}`, {
    method,
    headers: { ...headers, ...extraHeaders },
    body,
  });
  const text = await response.text();
  return { ok: response.ok, status: response.status, text };
}

// 1. Create the bucket (public: anyone can see the images) if it does not exist
const bucket = await call('GET', `/bucket/${BUCKET}`);
if (bucket.ok) {
  console.log(`Bucket "${BUCKET}" ya existe`);
} else {
  const created = await call(
    'POST',
    '/bucket',
    JSON.stringify({ id: BUCKET, name: BUCKET, public: true }),
    { 'Content-Type': 'application/json' },
  );
  if (!created.ok) {
    console.error(`No se pudo crear el bucket (${created.status}): ${created.text}`);
    process.exit(1);
  }
  console.log(`Bucket "${BUCKET}" creado (público)`);
}

// 2. Upload every image. x-upsert: if it already exists, it is replaced
const files = readdirSync(IMAGES_DIR).filter((file) => file.endsWith('.jpg'));
let failed = 0;
for (const file of files) {
  const result = await call(
    'POST',
    `/object/${BUCKET}/${file}`,
    readFileSync(join(IMAGES_DIR, file)),
    { 'Content-Type': 'image/jpeg', 'x-upsert': 'true' },
  );
  if (result.ok) {
    console.log(`✓ ${file}`);
  } else {
    failed++;
    console.error(`✗ ${file} (${result.status}): ${result.text}`);
  }
}
console.log(`\n${files.length - failed} de ${files.length} imágenes subidas`);
if (failed > 0) process.exit(1);

// 3. The SQL that changes the GitHub URLs for the Supabase ones
const publicBaseUrl = `${SUPABASE_URL}/storage/v1/object/public/${BUCKET}/`;
const sql = `-- Generated by database/scripts/upload-images.mjs
-- Changes the image URLs of seed.sql (GitHub) for the ones in Supabase Storage.
-- Paste it into the SQL Editor of the Supabase project.
UPDATE product_images
SET url = replace(url, '${SEED_BASE_URL}', '${publicBaseUrl}')
WHERE url LIKE '${SEED_BASE_URL}%';

-- Check: every URL should now start with ${publicBaseUrl}
SELECT url FROM product_images ORDER BY url LIMIT 5;
`;
writeFileSync(SQL_FILE, sql);
console.log(`\nAhora pega ${SQL_FILE} en el SQL Editor de Supabase.`);
console.log(`Ejemplo de imagen: ${publicBaseUrl}${files[0]}`);
